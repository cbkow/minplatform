#!/usr/bin/env python3
"""Generate crates/qcv-mxf/src/mxf_tags.rs from ExifTool's Image/ExifTool/MXF.pm tag table (canon row 137).

ExifTool (c) Phil Harvey, "free software; you can redistribute it and/or modify it under the same terms as Perl itself"
(GPL-1.0-or-later OR Artistic-1.0) -- GPL-compatible with this GPL-3.0-or-later workspace. Only the TABLE is taken (the
item ULs, their names and value kinds); the reader is our own Rust. Usage:
    python3 -I tools/mxf-tags/gen.py <path/to/MXF.pm> > crates/qcv-mxf/src/mxf_tags.rs
"""
import re, sys

src = open(sys.argv[1], encoding='utf-8').read()
start = src.index('%Image::ExifTool::MXF::Main = (')
end = src.index('%Image::ExifTool::MXF::Header')
body = src[start:end]
version = re.search(r"\$VERSION = '([^']+)'", src).group(1)

entries = []
i = 0
key_re = re.compile(r"^\s*'(060[ae]2b34\.[0-9a-f]{4}\.[0-9a-f]{4}\.[0-9a-f]{8}\.[0-9a-f]{8})'\s*=>\s*", re.M)
for m in key_re.finditer(body):
    # skip commented-out lines
    line_start = body.rfind('\n', 0, m.start()) + 1
    if body[line_start:m.start()].lstrip().startswith('#'): continue
    j = m.end()
    if body[j] == "'":   # 'UL' => 'Name'
        k = body.index("'", j + 1); entries.append((m.group(1), {'Name': body[j+1:k]})); continue
    assert body[j] == '{', body[j:j+40]
    depth = 0; k = j
    while True:
        c = body[k]
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: break
        k += 1
    txt = body[j+1:k]
    d = {}
    for f in ('Name', 'Type', 'Format', 'ValueConv'):
        mm = re.search(rf"\b{f}\s*=>\s*'([^']*)'", txt)
        if mm: d[f] = mm.group(1)
    if re.search(r"\bUnknown\s*=>\s*1", txt): d['Unknown'] = True
    for macro in ('duration', 'timestamp', 'localSet', 'header', 'componentDataDef'):
        if re.search(rf"%{macro}\b", txt): d[macro] = True
    if 'ConvLatLon' in txt: d['LatLon'] = True
    entries.append((m.group(1), d))

KNOWN = {'Alt','Lon','UL','AUID','PackageID','UMID','BatchOfUL','Position','UTF-16','Boolean','ProductVersion','UUID','GUID',
         'StrongReference','VersionType','Hex','StrongReferenceArray','WeakReference','Label','StrongReferenceBatch','Lat',
         'Timestamp','Length','UID'}
FORMATS = {'string':'Str','int8u':'U8','int8s':'I8','int16u':'U16','int16s':'I16','int32u':'U32','int32s':'I32','int64u':'U64',
           'int64s':'I64','float':'F32','double':'F64','rational64s':'R64','undef':'Undef','int16u[2]':'U16'}
def ul_bytes(ul):
    h = ul.replace('.', ''); return ', '.join(f'0x{h[i:i+2]}' for i in range(0, 32, 2))
out = []
out.append('//! GENERATED by tools/mxf-tags/gen.py from ExifTool MXF.pm v' + version + ' -- do not edit.')
out.append('//! The item / set ULs ExifTool names, their names and value kinds (ExifTool (c) Phil Harvey, Perl terms:')
out.append('//! GPL-1.0-or-later OR Artistic-1.0; only the table is taken, the reader is crates/qcv-mxf/src/mxf.rs).')
out.append('#![allow(clippy::all)]')
out.append('use crate::mxf::{Kind, Tag};')
out.append('pub(crate) static TAGS: &[Tag] = &[')
n = 0
for ul, d in entries:
    # Unknown entries are kept HIDDEN: ExifTool never outputs them, but decodes their values inside local sets (InstanceUID,
    # the strong references) to build the object tree, and skips them at the top level (body / footer partitions, SourceClip)
    hidden = 'true' if d.get('Unknown') else 'false'
    name = d.get('Name')
    if not name: continue
    if d.get('localSet'): kind = 'Kind::LocalSet'
    elif d.get('header'): kind = 'Kind::Partition'
    elif d.get('timestamp'): kind = 'Kind::Type("Timestamp")'
    elif d.get('Type') in KNOWN: kind = f'Kind::Type("{d["Type"]}")'
    elif d.get('Format') in FORMATS: kind = f'Kind::Format("{d["Format"]}")'
    elif d.get('Type') == 'Node': continue      # a node in the dictionary, never a value
    else: kind = 'Kind::Binary'
    conv = 'None'
    if d.get('LatLon'): conv = 'Some("latlon")'
    elif d.get('ValueConv') == '$val/10': conv = 'Some("div10")'
    out.append(f'    Tag {{ ul: [{ul_bytes(ul)}], name: "{name}", kind: {kind}, duration: {str(bool(d.get("duration"))).lower()}, conv: {conv}, hidden: {hidden} }},')
    n += 1
out.append('];')
sys.stdout.write('\n'.join(out) + '\n')
sys.stderr.write(f'{n} tags from MXF.pm v{version}\n')
